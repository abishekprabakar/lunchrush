import type { EngineKind } from './engines';
import type { LunchRushConfig, LunchRushResult } from './lunch-rush';

const ENGINE_LABEL: Record<EngineKind, string> = {
  'crdt-delta': 'CRDT, delta sync',
  'crdt-full': 'CRDT, full-state sync',
  baseline: 'Naive last-write-wins',
};

/** Render benchmark results as the markdown saved to results.md. Pure, so the same results give the same file. */
export function renderResults(results: LunchRushResult[], config: LunchRushConfig, command: string): string {
  const engines = [...new Set(results.map((r) => r.engine))];
  const seeds = [...new Set(results.map((r) => r.seed))];
  const of = (engine: EngineKind) => results.filter((r) => r.engine === engine);
  const minutes = (ms: number) => `${ms / 60_000} min`;
  const lines: string[] = [];

  lines.push('# Lunch-rush outage benchmark', '');
  lines.push(
    `Generated by \`${command}\`. Every number in this file comes from running the simulation in`,
    '`packages/sim`; nothing is estimated. The simulation is deterministic, so the same seeds produce',
    'this file byte for byte.',
    '',
  );

  lines.push('## Scenario', '');
  lines.push(
    `- Three devices (drive-thru tablet, counter register, kitchen display) and a cloud node.`,
    `- ${minutes(config.warmupMs)} online warm-up: ${config.warmup.orders} orders, ${config.warmup.statusEdits} planned status edits.`,
    `- The internet (every device-to-cloud link) goes down for ${minutes(config.outageMs)}: ${config.outage.orders} orders and ${config.outage.statusEdits} planned status edits happen during the outage.`,
    `- The internet comes back, then the run continues for ${minutes(config.tailMs)} with no new edits.`,
    config.driveThruSeesKitchen
      ? '- Every device can reach every other device on the LAN.'
      : '- The drive-thru tablet and the kitchen display cannot reach each other directly, so their edits relay through the counter (multihop).',
    `- Every node gossips every ${config.gossipIntervalMs} ms with each node it can reach.`,
    `- LAN links: ${linkText(config.lan)}.`,
    `- Internet links: ${linkText(config.internet)}, shared by the whole store.`,
    `- Device clock skew: ${Object.entries(config.clockSkewMs)
      .map(([id, ms]) => `${id} ${ms >= 0 ? '+' : ''}${ms} ms`)
      .join(', ')}.`,
    `- Seeds: ${seeds.join(', ')}. Each seed changes the workload and the network's random choices; every engine gets the same workload for a given seed.`,
    '',
  );

  lines.push(`## Results`, '');
  lines.push(`Median across ${seeds.length} seeds, with the range in parentheses when the runs differ.`, '');
  lines.push(
    '| Engine | Orders lost | Items lost | Status edits lost | Duplicates | Converged after reconnect | LAN bytes | Internet bytes | Total bytes | Redundant answers |',
    '| --- | --: | --: | --: | --: | --: | --: | --: | --: | --: |',
  );
  for (const engine of engines) {
    const runs = of(engine);
    const converge = runs.map((r) => r.convergeMs);
    lines.push(
      `| ${ENGINE_LABEL[engine]} | ${stat(runs.map((r) => r.ordersLost), String)} | ${stat(runs.map((r) => r.itemsLost), String)} | ${stat(runs.map((r) => r.statusLost), String)} | ${stat(runs.map((r) => r.duplicates), String)} | ${converge.includes(null) ? `did not converge in ${converge.filter((c) => c === null).length} of ${runs.length} runs` : stat(converge as number[], seconds)} | ${stat(runs.map((r) => r.bytesLan), megabytes)} | ${stat(runs.map((r) => r.bytesInternet), megabytes)} | ${stat(runs.map((r) => r.bytesLan + r.bytesInternet), megabytes)} | ${stat(runs.map(redundantShare), percentOf)} |`,
    );
  }
  lines.push('');

  const total = (engine: EngineKind) => of(engine).reduce((n, r) => n + r.bytesLan + r.bytesInternet, 0);
  if (engines.includes('crdt-delta') && engines.includes('crdt-full')) {
    lines.push(
      `Over all ${seeds.length} runs, delta sync sent **${(total('crdt-full') / total('crdt-delta')).toFixed(1)}x fewer bytes** than full-state sync, with the same merge and the same outcome.`,
      '',
    );
  }

  lines.push('## What the columns mean', '');
  lines.push(
    '- **Orders lost**: orders a device created that are missing on at least one node at the end.',
    '- **Items lost**: line items missing from orders that survived.',
    '- **Status edits lost**: surviving orders whose final status is not the furthest stage a device actually set.',
    '- **Duplicates**: order or item rows shown more than once, or orders nobody created. The network duplicates some messages on purpose.',
    '- **Converged after reconnect**: time from the internet coming back until all four nodes (three devices and the cloud) hold the same data. The naive baseline converges too, just onto data with holes in it.',
    '- **Bytes**: every message on the wire, as UTF-8 JSON, including version-vector summaries and messages the network then dropped.',
    '- **Redundant answers**: the share of sync-answer bytes that taught the receiver nothing new, because another peer had already sent the same edits. This happens most right after the reconnect, when the cloud asks all three devices at once and each answers with the same missing edits. An answer counts as useful if it contains even one new edit, so this column flatters full-state sync, whose useful answers are mostly things the receiver already had. Compare total bytes instead.',
    '- **Full-state sync** here is already the generous version: it only sends the whole state when the peer is missing something, instead of every round.',
    '',
  );

  lines.push('## Every run', '');
  lines.push(
    '| Engine | Seed | Orders | Items | Status edits applied / skipped | Lost (orders, items, status) | Duplicates | Identical at end | Converged after | LAN bytes | Internet bytes | Answer bytes / redundant | Messages sent / lost / duplicated |',
    '| --- | --: | --: | --: | --: | --: | --: | --- | --: | --: | --: | --: | --: |',
  );
  for (const r of results) {
    lines.push(
      `| ${ENGINE_LABEL[r.engine]} | ${r.seed} | ${r.ordersCreated} | ${r.itemsCreated} | ${r.statusApplied} / ${r.statusSkipped} | ${r.ordersLost}, ${r.itemsLost}, ${r.statusLost} | ${r.duplicates} | ${r.identicalAtEnd ? 'yes' : 'no'} | ${r.convergeMs === null ? 'never' : seconds(r.convergeMs)} | ${r.bytesLan} | ${r.bytesInternet} | ${r.payloadBytes} / ${r.redundantBytes} | ${r.messagesSent} / ${r.messagesLost} / ${r.messagesDuplicated} |`,
    );
  }
  lines.push(
    '',
    'Status edits are skipped when the device making them did not yet know the order, or already saw it at or past that stage. For the naive baseline this mostly means the order had been lost.',
    '',
  );
  return lines.join('\n');
}

/**
 * A short summary for README.md and EXPLAINER.md. bench.ts pastes it between
 * marker comments, so the numbers in the docs always come from the latest run.
 */
export function renderSummary(results: LunchRushResult[]): string {
  const engines = [...new Set(results.map((r) => r.engine))];
  const seeds = new Set(results.map((r) => r.seed)).size;
  const of = (engine: EngineKind) => results.filter((r) => r.engine === engine);
  const sumOf = (engine: EngineKind, pickBytes: (r: LunchRushResult) => number) =>
    of(engine).reduce((n, r) => n + pickBytes(r), 0);
  const lines = [
    `Measured by \`pnpm bench\` over ${seeds} seeded runs of the lunch-rush outage (medians; full details in [results.md](results.md)).`,
    '',
    '| Engine | Orders lost | Status edits lost | Converged after reconnect | Total bytes | Internet bytes |',
    '| --- | --: | --: | --: | --: | --: |',
  ];
  for (const engine of engines) {
    const runs = of(engine);
    const converge = runs.map((r) => r.convergeMs).filter((c): c is number => c !== null);
    lines.push(
      `| ${ENGINE_LABEL[engine]} | ${median(runs.map((r) => r.ordersLost))} | ${median(runs.map((r) => r.statusLost))} | ${converge.length === runs.length ? seconds(median(converge)) : 'did not always converge'} | ${megabytes(median(runs.map((r) => r.bytesLan + r.bytesInternet)))} | ${megabytes(median(runs.map((r) => r.bytesInternet)))} |`,
    );
  }
  if (engines.includes('crdt-delta') && engines.includes('crdt-full')) {
    const all = (r: LunchRushResult) => r.bytesLan + r.bytesInternet;
    const internet = (r: LunchRushResult) => r.bytesInternet;
    const redundant = sumOf('crdt-delta', (r) => r.redundantBytes) / sumOf('crdt-delta', (r) => r.payloadBytes);
    lines.push(
      '',
      `Delta sync sent ${(sumOf('crdt-full', all) / sumOf('crdt-delta', all)).toFixed(1)}x fewer bytes than full-state sync in total, but only ${(sumOf('crdt-full', internet) / sumOf('crdt-delta', internet)).toFixed(1)}x fewer over the internet. ${Math.round(redundant * 100)}% of the bytes in delta-sync answers taught the receiver nothing new.`,
    );
  }
  return lines.join('\n');
}

function median(values: number[]): number {
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.floor(sorted.length / 2)];
}

function linkText(link: LunchRushConfig['lan']): string {
  return `${link.latencyMs} ms latency plus up to ${link.jitterMs} ms jitter, ${percent(link.loss)} loss, ${percent(link.duplicate)} duplicated, ${link.bytesPerSecond / 1000} KB/s`;
}

function stat(values: number[], format: (v: number) => string): string {
  const sorted = [...values].sort((a, b) => a - b);
  const median = sorted[Math.floor(sorted.length / 2)];
  const min = sorted[0];
  const max = sorted[sorted.length - 1];
  return min === max ? format(median) : `${format(median)} (${format(min)}–${format(max)})`;
}

function redundantShare(r: LunchRushResult): number {
  return r.payloadBytes === 0 ? 0 : r.redundantBytes / r.payloadBytes;
}

function percentOf(share: number): string {
  return `${Math.round(share * 100)}%`;
}

function percent(p: number): string {
  return `${+(p * 100).toFixed(2)}%`;
}

function seconds(ms: number): string {
  return `${(ms / 1000).toFixed(2)} s`;
}

function megabytes(bytes: number): string {
  return `${(bytes / 1_000_000).toFixed(2)} MB`;
}
